"""
Decision Engine Port
Defines interfaces and data models for proposing actionable interventions from digest flags and anomalies.
"""

from abc import ABC, abstractmethod
from typing import Dict, Any, List, Optional, Literal
from datetime import datetime, timezone
from pydantic import BaseModel, Field, ConfigDict

from domain.actions import ActionType


class DecisionContext(BaseModel):
    """
    Context supplied to DecisionPort containing the triggering signal and tenant configuration.
    """
    model_config = ConfigDict(extra="forbid")

    tenant_id: str
    signal_type: Literal["digest_flag", "idle_cart"]
    signal_payload: Dict[str, Any]
    signal_dedupe_key: str
    as_of: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    tenant_config: Dict[str, Any] = Field(default_factory=dict)


class DecisionCandidate(BaseModel):
    """
    An individual action candidate generated by a decision engine before policy check and planning.
    """
    model_config = ConfigDict(extra="forbid")

    action_type: ActionType
    target_module: Literal["module_1_loyalty", "module_2_behavior", "module_3_ads", "notification"]
    target_type: str = Field(..., description="customer, campaign, system, audience")
    target_id: str
    customer_id: Optional[str] = None
    anonymous_id: Optional[str] = None

    parameters: BaseModel = Field(..., description="Strongly typed parameters model")
    reasoning_summary: str = Field(..., description="Fact-grounded rationale for the proposed action")
    evidence_citations: List[str] = Field(default_factory=list, description="Grounding facts from metric calculations")

    priority_score: float = Field(default=0.5, ge=0.0, le=1.0, description="Heuristic priority for ranking")
    calibrated_probability: Optional[float] = Field(default=None, ge=0.0, le=1.0, description="Calibrated outcome probability")
    llm_self_reported_confidence: Optional[float] = Field(default=None, ge=0.0, le=1.0, description="Raw self-reported confidence from LLM (never feeds autonomy check)")
    is_holdout: bool = Field(default=False, description="True if allocated to control group")


class DecisionPort(ABC):
    """
    Port for generating action candidates from signals.
    """

    @abstractmethod
    def propose_candidates(self, context: DecisionContext) -> List[DecisionCandidate]:
        """
        Generates candidate actions for a given decision context.
        Returns a list of DecisionCandidate (can be empty if DO_NOTHING or non-action).
        """
        pass
